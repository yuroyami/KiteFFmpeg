typedef struct {
    const unsigned char *bytes;
    int64_t size;
    int64_t position;
} memory_source;

static int memory_read(void *opaque, unsigned char *buf, int len)
{
    memory_source *m = (memory_source *)opaque;
    int64_t left = m->size - m->position;
    int n = left < len ? (int)left : len;
    if (n <= 0) return KC_IO_EOF;
    memcpy(buf, m->bytes + m->position, (size_t)n);
    m->position += n;
    return n;
}

static int64_t memory_seek(void *opaque, int64_t offset, int whence)
{
    memory_source *m = (memory_source *)opaque;
    int64_t target = whence == SEEK_SET ? offset : whence == SEEK_CUR ? m->position + offset : m->size + offset;
    if (target < 0 || target > m->size) return KC_IO_ERR;
    m->position = target;
    return target;
}

/* Opens [bytes] from memory, finds its stream info, and answers the duration's origin. */
static int origin_of(const unsigned char *bytes, int64_t size, int64_t *duration)
{
    memory_source source = { bytes, size, 0 };
    kc_fmt_ctx *ctx = NULL;
    int origin;

    KC_EQ_INT(ffkmp_fmt_open_input_io(&ctx, &source, memory_read, memory_seek, size,
                                      NULL, NULL, 0, NULL, NULL), 0);
    KC_NOT_NULL(ctx);
    KC_CHECK(ffkmp_fmt_find_stream_info(ctx) >= 0);
    *duration = ffkmp_fmt_duration(ctx);
    origin = ffkmp_fmt_duration_origin(ctx);
    ffkmp_fmt_close_input_io(&ctx);
    return origin;
}

static void case_a_length_without_a_header_is_an_estimate(void)
{
    int64_t duration = 0;
    int origin;

    kc_case("an MP3 without its Xing header has a length estimated from its bit rate");
    origin = origin_of(kc_mp3_without_xing, (int64_t)sizeof(kc_mp3_without_xing), &duration);
    kc_detail("origin=%d duration=%lld", origin, (long long)duration);
    KC_EQ_INT(origin, 2);
    KC_CHECK(duration > 0);
}

static void case_a_declared_length_is_not(void)
{
    /* 16-bit stereo 48 kHz over 192000 bytes of silence: one second, declared by the data chunk. */
    static const unsigned char header[44] = {
        'R', 'I', 'F', 'F', 0x24, 0xEE, 0x02, 0, 'W', 'A', 'V', 'E',
        'f', 'm', 't', ' ', 16, 0, 0, 0, 1, 0, 2, 0,
        0x80, 0xBB, 0, 0, 0x00, 0xEE, 0x02, 0, 4, 0, 16, 0,
        'd', 'a', 't', 'a', 0x00, 0xEE, 0x02, 0,
    };
    int64_t size = (int64_t)sizeof(header) + 192000;
    unsigned char *wav = calloc(1, (size_t)size);
    int64_t duration = 0;
    int origin;

    kc_case("a WAV whose header states its length is not an estimate");
    KC_NOT_NULL(wav);
    memcpy(wav, header, sizeof(header));
    origin = origin_of(wav, size, &duration);
    kc_detail("origin=%d duration=%lld", origin, (long long)duration);
    KC_EQ_INT(origin, 1);
    KC_EQ_I64(duration, 1000000);
    free(wav);
}

static void case_no_context_has_no_origin(void)
{
    kc_case("a NULL context answers -1");
    KC_EQ_INT(ffkmp_fmt_duration_origin(NULL), -1);
}

int main(void)
{
    kc_suite_begin("test_duration_origin");

    case_a_length_without_a_header_is_an_estimate();
    case_a_declared_length_is_not();
    case_no_context_has_no_origin();

    return kc_suite_end();
}
