typedef struct {
    const unsigned char *bytes;
    int64_t size;
    int64_t position;
} memory_source;

static int memory_read(void *opaque, unsigned char *buf, int len)
{
    memory_source *m = (memory_source *)opaque;
    int64_t left = m->size - m->position;
    int n = left < len ? (int)left : len;
    if (n <= 0) return KC_IO_EOF;
    memcpy(buf, m->bytes + m->position, (size_t)n);
    m->position += n;
    return n;
}

static int64_t memory_seek(void *opaque, int64_t offset, int whence)
{
    memory_source *m = (memory_source *)opaque;
    int64_t target = whence == SEEK_SET ? offset : whence == SEEK_CUR ? m->position + offset : m->size + offset;
    if (target < 0 || target > m->size) return KC_IO_ERR;
    m->position = target;
    return target;
}

typedef struct {
    int spherical_found;
    int spherical[9];
    int stereo_found;
    int stereo[9];
} reading;

static void reading_reset(reading *r)
{
    r->spherical_found = -1;
    r->stereo_found = -1;
    for (int i = 0; i < 9; i++) r->spherical[i] = r->stereo[i] = -7;
}

/* Opens [bytes] from memory and reads the first stream's mapping and layout into [r]. */
static void read_file(const unsigned char *bytes, int64_t size, reading *r)
{
    memory_source source = { bytes, size, 0 };
    kc_fmt_ctx *ctx = NULL;

    reading_reset(r);
    KC_EQ_INT(ffkmp_fmt_open_input_io(&ctx, &source, memory_read, memory_seek, size,
                                      NULL, NULL, 0, NULL, NULL), 0);
    KC_NOT_NULL(ctx);
    KC_CHECK(ffkmp_fmt_find_stream_info(ctx) >= 0);
    KC_CHECK(ffkmp_fmt_nb_streams(ctx) >= 1);
    kc_codec_par *par = ffkmp_stream_codecpar(ffkmp_fmt_stream(ctx, 0));
    r->spherical_found = ffkmp_codecpar_spherical(par, r->spherical);
    r->stereo_found = ffkmp_codecpar_stereo3d(par, r->stereo);
    kc_detail("spherical=%d [%d %d %d %d %d %d %d %d %d] stereo=%d [%d %d %d %d %d %d %d %d %d]",
              r->spherical_found, r->spherical[0], r->spherical[1], r->spherical[2], r->spherical[3],
              r->spherical[4], r->spherical[5], r->spherical[6], r->spherical[7], r->spherical[8],
              r->stereo_found, r->stereo[0], r->stereo[1], r->stereo[2], r->stereo[3], r->stereo[4],
              r->stereo[5], r->stereo[6], r->stereo[7], r->stereo[8]);
    ffkmp_fmt_close_input_io(&ctx);
}

static void expect_ints(const int *actual, const int *expected, int count)
{
    for (int i = 0; i < count; i++) KC_EQ_INT(actual[i], expected[i]);
}

/* A 16.16 fixed-point angle from a whole number of hundredths of a degree. */
#define KC_DEGREES(hundredths) ((int)((hundredths) * 65536LL / 100))

/* The four stereo fields an FFmpeg without them reads as: no primary eye, no baseline, 0/1 and 0/1. */
static const int kc_stereo_tail_none[6] = { 0, 0, 0, 1, 0, 1 };

static void expect_stereo(const reading *r, int type, int inverted, int view)
{
    KC_EQ_INT(r->stereo_found, 1);
    KC_EQ_INT(r->stereo[0], type);
    KC_EQ_INT(r->stereo[1], inverted);
    KC_EQ_INT(r->stereo[2], view);
    expect_ints(r->stereo + 3, kc_stereo_tail_none, 6);
}

static void expect_untouched(const int *out)
{
    for (int i = 0; i < 9; i++) KC_EQ_INT(out[i], -7);
}

static void case_matroska_equirectangular_and_bottom_top(void)
{
    reading r;
    const int spherical[9] = { AV_SPHERICAL_EQUIRECTANGULAR, KC_DEGREES(9000), KC_DEGREES(-3000),
                               KC_DEGREES(1500), 0, 0, 0, 0, 0 };

    kc_case("a Matroska equirectangular track turned 90, -30 and 15 reads with its turn, and its StereoMode 2 as top and bottom inverted");
    read_file(kc_mkv_equirectangular, (int64_t)sizeof(kc_mkv_equirectangular), &r);
    KC_EQ_INT(r.spherical_found, 1);
    expect_ints(r.spherical, spherical, 9);
    expect_stereo(&r, AV_STEREO3D_TOPBOTTOM, 1, AV_STEREO3D_VIEW_PACKED);
}

static void case_matroska_tile_bounds(void)
{
    reading r;
    const int spherical[9] = { AV_SPHERICAL_EQUIRECTANGULAR_TILE, KC_DEGREES(3325), KC_DEGREES(725), 0,
                               0x10000000, 0x40000000, 0x08000000, 0x20000000, 0 };

    kc_case("a Matroska tile reads its four bounds as 0.32 fixed point, left, top, right and bottom, and no stereo layout");
    read_file(kc_mkv_tile, (int64_t)sizeof(kc_mkv_tile), &r);
    KC_EQ_INT(r.spherical_found, 1);
    expect_ints(r.spherical, spherical, 9);
    KC_EQ_INT(r.stereo_found, 0);
    expect_untouched(r.stereo);
}

