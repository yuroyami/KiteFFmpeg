#define KC_TS_PACKET 188

typedef struct {
    const unsigned char *bytes;
    int64_t size;
    int64_t position;
} memory_source;

static int memory_read(void *opaque, unsigned char *buf, int len)
{
    memory_source *m = (memory_source *)opaque;
    int64_t left = m->size - m->position;
    int n = left < len ? (int)left : len;
    if (n <= 0) return KC_IO_EOF;
    memcpy(buf, m->bytes + m->position, (size_t)n);
    m->position += n;
    return n;
}

static int64_t memory_seek(void *opaque, int64_t offset, int whence)
{
    memory_source *m = (memory_source *)opaque;
    int64_t target = whence == SEEK_SET ? offset : whence == SEEK_CUR ? m->position + offset : m->size + offset;
    if (target < 0 || target > m->size) return KC_IO_ERR;
    m->position = target;
    return target;
}

/* The CRC that ends an MPEG section, over the [len] bytes before it, as FFmpeg's writer computes it. */
static uint32_t section_crc(const unsigned char *section, size_t len)
{
    return av_bswap32(av_crc(av_crc_get_table(AV_CRC_32_IEEE), UINT32_MAX, section, len));
}

static uint32_t read_u32(const unsigned char *d)
{
    return (uint32_t)d[0] << 24 | (uint32_t)d[1] << 16 | (uint32_t)d[2] << 8 | d[3];
}

/* Takes programme [number] out of every programme association table in [ts], and answers how many
 * tables it rewrote, or -1 when a table is not what FFmpeg 6.1 writes. Each table fits one packet
 * and starts in it, so the entry is cut, the length shortened, the CRC written again and the packet
 * padded with 0xff, as a writer pads it. */
static int drop_from_association_table(unsigned char *ts, size_t size, int number)
{
    int rewritten = 0;
    for (size_t at = 0; at + KC_TS_PACKET <= size; at += KC_TS_PACKET) {
        unsigned char *p = ts + at;
        const int pid = (p[1] & 0x1f) << 8 | p[2];
        if (p[0] != 0x47) return -1;
        if (pid != 0 || !(p[1] & 0x40)) continue;
        size_t i = 4;
        if (p[3] & 0x20) i += 1u + p[4];
        i += 1u + p[i]; /* the pointer field */
        unsigned char *section = p + i;
        const size_t length = (size_t)((section[1] & 0x0f) << 8 | section[2]);
        const size_t whole = 3 + length;
        if (section[0] != 0 || i + whole > KC_TS_PACKET || length < 9) return -1;
        if (read_u32(section + whole - 4) != section_crc(section, whole - 4)) return -1;
        size_t entry = 8;
        while (entry + 4 <= whole - 4 && (section[entry] << 8 | section[entry + 1]) != number) entry += 4;
        if (entry + 4 > whole - 4) return -1;
        memmove(section + entry, section + entry + 4, whole - entry - 4);
        const size_t shorter = whole - 4;
        section[1] = (unsigned char)((section[1] & 0xf0) | ((shorter - 3) >> 8));
        section[2] = (unsigned char)((shorter - 3) & 0xff);
        const uint32_t crc = section_crc(section, shorter - 4);
        section[shorter - 4] = (unsigned char)(crc >> 24);
        section[shorter - 3] = (unsigned char)(crc >> 16);
        section[shorter - 2] = (unsigned char)(crc >> 8);
        section[shorter - 1] = (unsigned char)crc;
        memset(section + shorter, 0xff, KC_TS_PACKET - i - shorter);
        rewritten++;
    }
    return rewritten;
}

static kc_fmt_ctx *open_memory(memory_source *source)
{
    kc_fmt_ctx *ctx = NULL;
    KC_EQ_INT(ffkmp_fmt_open_input_io(&ctx, source, memory_read, memory_seek, source->size,
                                      NULL, NULL, 0, NULL, NULL), 0);
    KC_NOT_NULL(ctx);
    if (ctx) KC_CHECK(ffkmp_fmt_find_stream_info(ctx) >= 0);
    return ctx;
}

/* The value of [key] in a borrowed dictionary, or NULL. */
static const char *tag(kc_dict *dict, const char *key)
{
    for (kc_dict_entry *e = ffkmp_dict_get(dict, NULL); e; e = ffkmp_dict_get(dict, e))
        if (strcmp(ffkmp_dict_entry_key(e), key) == 0) return ffkmp_dict_entry_value(e);
    return NULL;
}

/* Programme [index] of [ctx] has [id], [number], the [count] streams in [streams] in that order, and
 * the service name [name] from FFmpeg. */
static void expect_program(kc_fmt_ctx *ctx, int index, int id, int number, const int *streams, int count,
                           const char *name)
{
    int got_id = -7, got_number = -7, got_count = -7;
    KC_EQ_INT(ffkmp_fmt_program_get(ctx, index, &got_id, &got_number, &got_count), 0);
    kc_detail("programme %d: id=%d number=%d streams=%d", index, got_id, got_number, got_count);
    KC_EQ_INT(got_id, id);
    KC_EQ_INT(got_number, number);
    KC_EQ_INT(got_count, count);
    for (int position = 0; position < count && position < got_count; position++)
        KC_EQ_INT(ffkmp_fmt_program_stream(ctx, index, position), streams[position]);
    kc_dict *tags = ffkmp_fmt_program_metadata(ctx, index);
    KC_NOT_NULL(tags);
    KC_EQ_STR(tag(tags, "service_name"), name);
    KC_EQ_STR(tag(tags, "service_provider"), "FFmpeg");
}

static void case_two_channels_read_as_two_programmes(void)
{
    static const int channel_a[2] = { 0, 1 }, channel_b[2] = { 2, 3 };
    memory_source source = { kc_ts_two_programs, (int64_t)sizeof(kc_ts_two_programs), 0 };

    kc_case("a transport stream with two channels reads two programmes with their numbers, streams and names");
    kc_fmt_ctx *ctx = open_memory(&source);
    if (!ctx) return;
    KC_EQ_INT(ffkmp_fmt_program_count(ctx), 2);
    KC_EQ_INT(ffkmp_fmt_nb_streams(ctx), 4);
    expect_program(ctx, 0, 1, 1, channel_a, 2, "ChannelA");
    expect_program(ctx, 1, 2, 2, channel_b, 2, "ChannelB");
    ffkmp_fmt_close_input_io(&ctx);
}

static void case_a_channel_only_the_service_table_names_has_no_number_and_no_streams(void)
{
    static const int channel_a[2] = { 0, 1 };
    unsigned char *ts = malloc(sizeof(kc_ts_two_programs));
    memory_source source = { ts, (int64_t)sizeof(kc_ts_two_programs), 0 };

    kc_case("a channel the service table names and the association table does not reads with number 0 and no streams");
    KC_NOT_NULL(ts);
    if (!ts) return;
    memcpy(ts, kc_ts_two_programs, sizeof(kc_ts_two_programs));
    const int rewritten = drop_from_association_table(ts, sizeof(kc_ts_two_programs), 2);
    kc_detail("association tables rewritten: %d", rewritten);
    KC_CHECK(rewritten > 0);
    kc_fmt_ctx *ctx = open_memory(&source);
    if (ctx) {
        KC_EQ_INT(ffkmp_fmt_program_count(ctx), 2);
        KC_EQ_INT(ffkmp_fmt_nb_streams(ctx), 4);
        expect_program(ctx, 0, 1, 1, channel_a, 2, "ChannelA");
        expect_program(ctx, 1, 2, 0, NULL, 0, "ChannelB");
        KC_EQ_INT(ffkmp_fmt_program_stream(ctx, 1, 0), AVERROR(EINVAL));
        ffkmp_fmt_close_input_io(&ctx);
    }
    free(ts);
}

