typedef struct {
    const unsigned char *bytes;
    int64_t size;
    int64_t position;
} memory_source;

static int memory_read(void *opaque, unsigned char *buf, int len)
{
    memory_source *m = (memory_source *)opaque;
    int64_t left = m->size - m->position;
    int n = left < len ? (int)left : len;
    if (n <= 0) return KC_IO_EOF;
    memcpy(buf, m->bytes + m->position, (size_t)n);
    m->position += n;
    return n;
}

static int64_t memory_seek(void *opaque, int64_t offset, int whence)
{
    memory_source *m = (memory_source *)opaque;
    /* FFmpeg's size probe reaches the reader and moves nothing (#177). */
    if (whence == AVSEEK_SIZE) return m->size;
    int64_t target = whence == SEEK_SET ? offset : whence == SEEK_CUR ? m->position + offset : m->size + offset;
    if (target < 0 || target > m->size) return KC_IO_ERR;
    m->position = target;
    return target;
}

/* Opens [bytes] from memory and reads the first stream's crop into out[4]; answers the helper's result. */
static int crop_of(const unsigned char *bytes, int64_t size, int *out)
{
    memory_source source = { bytes, size, 0 };
    kc_fmt_ctx *ctx = NULL;
    int found;

    KC_EQ_INT(ffkmp_fmt_open_input_io(&ctx, &source, memory_read, memory_seek, size,
                                      NULL, NULL, 0, NULL, NULL), 0);
    KC_NOT_NULL(ctx);
    KC_CHECK(ffkmp_fmt_find_stream_info(ctx) >= 0);
    KC_CHECK(ffkmp_fmt_nb_streams(ctx) >= 1);
    found = ffkmp_codecpar_frame_cropping(ffkmp_stream_codecpar(ffkmp_fmt_stream(ctx, 0)), out);
    ffkmp_fmt_close_input_io(&ctx);
    return found;
}

static void expect_bottom_eight(const unsigned char *bytes, int64_t size)
{
    int out[4] = { -1, -1, -1, -1 };
    int found = crop_of(bytes, size, out);
    kc_detail("found=%d top=%d bottom=%d left=%d right=%d", found, out[0], out[1], out[2], out[3]);
#if KC_READS_CROP
    KC_EQ_INT(found, 1);
    KC_EQ_INT(out[0], 0);
    KC_EQ_INT(out[1], 8);
    KC_EQ_INT(out[2], 0);
    KC_EQ_INT(out[3], 0);
#else
    KC_EQ_INT(found, 0);
#endif
}

static void case_a_matroska_pixel_crop_is_read(void)
{
    kc_case("a Matroska track cropped 8 rows at the bottom reports 8 at the bottom and 0 elsewhere");
    expect_bottom_eight(kc_mkv_cropped, (int64_t)sizeof(kc_mkv_cropped));
}

static void case_an_mp4_clean_aperture_is_read(void)
{
    kc_case("an MP4 clean aperture of 16 by 8 moved up by 4 reports 8 at the bottom");
    expect_bottom_eight(kc_mp4_clean_aperture, (int64_t)sizeof(kc_mp4_clean_aperture));
}

static void case_a_stream_without_one_has_none(void)
{
    /* A WAV header and a little silence: a stream with no coded side data at all. */
    static const unsigned char header[44] = {
        'R', 'I', 'F', 'F', 0xA4, 0x0F, 0, 0, 'W', 'A', 'V', 'E',
        'f', 'm', 't', ' ', 16, 0, 0, 0, 1, 0, 1, 0,
        0x40, 0x1F, 0, 0, 0x80, 0x3E, 0, 0, 2, 0, 16, 0,
        'd', 'a', 't', 'a', 0x80, 0x0F, 0, 0,
    };
    int64_t size = (int64_t)sizeof(header) + 4000;
    unsigned char *wav = calloc(1, (size_t)size);
    int out[4] = { -1, -1, -1, -1 };

    kc_case("a stream without a container crop reports none and leaves out alone");
    KC_NOT_NULL(wav);
    memcpy(wav, header, sizeof(header));
    KC_EQ_INT(crop_of(wav, size, out), 0);
    KC_EQ_INT(out[0], -1);
    free(wav);
}

static void case_null_arguments_are_refused(void)
{
    int out[4];

    kc_case("a NULL argument answers EINVAL");
    KC_CHECK(ffkmp_codecpar_frame_cropping(NULL, out) < 0);
}

int main(void)
{
    kc_suite_begin("test_crop");

    case_a_matroska_pixel_crop_is_read();
    case_an_mp4_clean_aperture_is_read();
    case_a_stream_without_one_has_none();
    case_null_arguments_are_refused();

    return kc_suite_end();
}
