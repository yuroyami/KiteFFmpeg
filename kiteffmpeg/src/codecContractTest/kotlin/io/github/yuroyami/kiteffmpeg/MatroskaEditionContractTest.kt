package io.github.yuroyami.kiteffmpeg

import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * A Matroska file's chapter list is its default edition's chapters, less the ones a viewer is not
 * meant to see and the ones that play another file (#172).
 *
 * A file can hold several editions of its chapters, such as a theatrical and an extended cut, and
 * RFC 9559 makes the first one flagged default the one a player uses, or the first one when none is.
 * FFmpeg 9.0.2 read the chapters of every edition into one list and kept each that started later
 * than the one before it, so this file read as two chapters of its first edition and the last of its
 * second. It also listed a hidden chapter, a disabled one, and one that an ordered edition plays from
 * another file, at that file's times. The fix is the FFmpeg patch `0013`, so this test fails on a
 * tree built before it.
 */
class MatroskaEditionContractTest {

    private fun chapters(): List<Chapter> =
        MediaSource.open(materializeContractMedia(EditionsMatroska.bytes, EditionsMatroska.sha256)).use { it.chapters }

    @Test
    fun theDefaultEditionIsReadWithoutItsHiddenDisabledOrLinkedChapters() {
        val chapters = chapters()
        assertEquals(listOf(21L to "Opening", 25L to "Story", 26L to "Credits"), chapters.map { it.id to it.title })
        assertEquals(
            listOf(0L to 1_000_000L, 2_000_000L to 4_000_000L, 4_000_000L to 6_000_000L),
            chapters.map { it.startMicros to it.endMicros },
        )
    }

    @Test
    fun aTagThatTargetsAChapterOfTheDefaultEditionReachesIt() {
        assertEquals(listOf(null, "Someone", null), chapters().map { it.metadata["ARTIST"] })
    }
}

